import { ref } from 'vue';

const messages: Record<string, Record<string, string>> = { 'en-US': enUS, 'zh-CN': zhCN, 'zh-TW': zhTW };

export const currentLocale = ref(localStorage.getItem('locale') || 'zh-CN');

export function t(key: string, params?: Record<string, string>): string {
  const msgs = messages[currentLocale.value] || messages.en;
  let msg = msgs[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      msg = msg.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    });
  }
  return msg;
}

export function setLocale(locale: string) {
  currentLocale.value = locale;
  localStorage.setItem('locale', locale);
}

export function getLocale(): string {
  return currentLocale.value;
}

export { messages };
